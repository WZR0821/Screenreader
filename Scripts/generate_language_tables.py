#!/usr/bin/env python3
"""Regenerate ScreenTranslate/Core/LanguageScriptTables.swift.

The tables tell Chinese from Japanese by which characters a text uses. They are
derived from three national character sets with Python's own codecs, so the
result can be reproduced and checked:

  GB 2312 level 1   3,755 everyday simplified Chinese characters
  Big5 level 1      5,401 everyday traditional Chinese characters
  JIS X 0208 lv. 1  2,965 everyday Japanese kanji

A character that everyday Chinese uses and everyday Japanese does not is
evidence of Chinese, and the reverse for Japanese. Characters all three share
say nothing and are left out.
"""
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / 'ScreenTranslate/Core/LanguageScriptTables.swift'


def rows(codec, lead_offset, first, last):
    found = []
    for row in range(first, last + 1):
        for column in range(1, 95):
            try:
                found.append(bytes([lead_offset + row, 0xA0 + column]).decode(codec))
            except UnicodeDecodeError:
                pass
    return found


def big5_level1():
    found = []
    for lead in range(0xA4, 0xC7):
        for trail in list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF)):
            if lead == 0xC6 and trail > 0x7E:
                continue
            try:
                found.append(bytes([lead, trail]).decode('big5'))
            except UnicodeDecodeError:
                pass
    return found


def encodable(character, codec):
    try:
        character.encode(codec)
        return True
    except UnicodeEncodeError:
        return False


def is_han(character):
    return 0x3400 <= ord(character) <= 0x9FFF or 0xF900 <= ord(character) <= 0xFAFF


gb1 = [c for c in rows('gb2312', 0xA0, 16, 55) if is_han(c)]
jis1 = [c for c in rows('euc_jp', 0xA0, 16, 47) if is_han(c)]
b1 = [c for c in big5_level1() if is_han(c)]
assert (len(gb1), len(jis1), len(b1)) == (3755, 2965, 5401), (len(gb1), len(jis1), len(b1))
jis1_set = set(jis1)

# Everyday Chinese that everyday Japanese does not use.
chinese = [c for c in dict.fromkeys(gb1 + b1) if c not in jis1_set]
simplified_form = {c for c in gb1 if not encodable(c, 'big5')}
traditional_form = {c for c in b1 if not encodable(c, 'gb2312')}

tables = {
    # Evidence of Chinese, written the simplified way: 这 们 说 对 发.
    'chineseSimplified': [c for c in chinese if c in simplified_form],
    # Evidence of Chinese, written the traditional way: 們 說 對 發 嗎.
    'chineseTraditional': [c for c in chinese if c in traditional_form],
    # Evidence of Chinese in either writing: 你 很 它 哪 怎.
    'chineseCommon': [c for c in chinese if c not in simplified_form and c not in traditional_form],
    # Simplified forms Japanese writes the same way: 国 学 会 点 来.
    'sharedSimplified': [c for c in gb1 if c in simplified_form and c in jis1_set],
    # Traditional forms Japanese writes the same way: 東 語 時 間 車.
    'sharedTraditional': [c for c in b1 if c in traditional_form and c in jis1_set],
    # Japanese forms neither Chinese writing has: 駅 円 図 楽 気 売 読.
    'japaneseOnly': [c for c in jis1 if not encodable(c, 'gb2312') and not encodable(c, 'big5')],
}
seen = set()
for name, characters in tables.items():
    assert characters and len(set(characters)) == len(characters), name
    assert seen.isdisjoint(characters), name
    seen.update(characters)

comments = {
    'chineseSimplified': 'Chinese only, simplified form: 这 们 说 对 发.',
    'chineseTraditional': 'Chinese only, traditional form: 們 說 對 發 嗎.',
    'chineseCommon': 'Chinese only, same in both forms: 你 很 它 哪 怎.',
    'sharedSimplified': 'Simplified forms that Japanese shares: 国 学 会 点 来.',
    'sharedTraditional': 'Traditional forms that Japanese shares: 東 語 時 間 車.',
    'japaneseOnly': 'Japanese forms that neither Chinese writing has: 駅 円 図 楽 気.',
}
lines = [
    '// Generated by Scripts/generate_language_tables.py from GB 2312 level 1,',
    '// Big5 level 1 and JIS X 0208 level 1. Do not edit by hand.',
    '',
    'enum LanguageScriptTables {',
]
for name, characters in tables.items():
    lines.append(f'    /// {comments[name]} {len(characters)} characters.')
    lines.append(f'    static let {name} = """')
    text = ''.join(characters)
    chunks = [text[i:i + 50] for i in range(0, len(text), 50)]
    for index, chunk in enumerate(chunks):
        lines.append('    ' + chunk + ('\\' if index < len(chunks) - 1 else ''))
    lines.append('    """')
    lines.append('')
lines[-1] = '}'
OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print({name: len(characters) for name, characters in tables.items()})
